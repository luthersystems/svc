func (jsWide512) MarshalJSON() ([]byte, error) { return []byte(`{}`), nil }

type jsWideOuter struct{ jsWide512 }

// TestEmbedSearchChargesChildFields: deciding whether an embedded struct
// declares its MarshalJSON reads its field list, and that is charged (a
// step per 2 fields), the same on every walk.
func TestEmbedSearchChargesChildFields(t *testing.T) {
	var steps [2]int64
	for i := range steps {
		bud := &goBudget{max: 1 << 40}
		require.NoError(t, goJSONCost(bud, reflect.ValueOf(jsWideOuter{}), 0))
		steps[i] = bud.used
	}
	require.GreaterOrEqual(t, steps[0], int64(512/2), "the child's 512 fields")
	require.Equal(t, steps[0], steps[1], "cold and warm alike")
}
